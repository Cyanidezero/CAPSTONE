/**
 * Helper to retrieve a concise, simple fun fact for any crop in specified language
 */
export function getVegetableFunFact(crop, lang = 'en') {
  if (!crop) return '';
  const isFil = lang === 'fil';
  const cleanId = String(crop.id || '').toLowerCase().trim();
  const cleanName = String(crop.name || '').toLowerCase().trim();
  const cleanFil = String(crop.filipinoName || '').toLowerCase().trim();

  // 1. Direct key match
  if (VEGETABLE_FUN_FACTS[cleanId]) {
    return isFil ? VEGETABLE_FUN_FACTS[cleanId].fil : VEGETABLE_FUN_FACTS[cleanId].en;
  }
  if (VEGETABLE_FUN_FACTS[cleanName]) {
    return isFil ? VEGETABLE_FUN_FACTS[cleanName].fil : VEGETABLE_FUN_FACTS[cleanName].en;
  }
  if (VEGETABLE_FUN_FACTS[cleanFil]) {
    return isFil ? VEGETABLE_FUN_FACTS[cleanFil].fil : VEGETABLE_FUN_FACTS[cleanFil].en;
  }

  // 2. Substring search in dictionary
  for (const [key, factObj] of Object.entries(VEGETABLE_FUN_FACTS)) {
    if (cleanName.includes(key) || cleanId.includes(key) || cleanFil.includes(key) || key.includes(cleanName)) {
      return isFil ? factObj.fil : factObj.en;
    }
  }

  // 3. Fallback generic plant fact
  return isFil
    ? `Ang ${crop.filipinoName || crop.name} ay masustansyang short-cycle na gulay na madaling patubuin sa bakuran o paso.`
    : `${crop.name || 'This vegetable'} is a nutrient-rich, fast-growing urban vegetable ideal for healthy home gardens.`;
}
